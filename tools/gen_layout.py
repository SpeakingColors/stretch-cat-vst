#!/usr/bin/env python3
"""Generates src/editor/Layout.h from docs/mockup/layout.json (made by tools/dump_layout.py from the approved mockup).
Every position, size, label and tooltip in the native editor comes from the mockup this way. Coordinates are relative to
the panel (the mockup window minus the 30 px wood cheeks). The mockup's FX rack has two sections the plugin does not have
yet (Detune and widen, Output); they are left out, which makes the rack fit without a scroll bar (see ROADMAP).
Run from the repo root."""
import json
d = json.load(open('docs/mockup/layout.json'))
OX = 30.0
def f(v):
    t = '%g' % v
    if 'e' in t: t = '%.3f' % v
    return t + ('' if '.' in t else '.0') + 'f'
def rc(r): return '{ ' + ', '.join(f(v - (OX if i == 0 else 0)) if i == 0 else f(v) for i, v in enumerate(r)) + ' }'
def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
ZERO = '{ 0, 0, 0, 0 }'
secs = d['rkSecs']
def secOf(y):
    for s in secs:
        if s['r'][1] - 1 <= y < s['r'][1] + s['r'][3] - 1: return s['h'].split('On')[0].replace('Detune and widen', 'Detune').replace('Output', 'Output')
    return ''
def secName(h):
    for n in ('Filter', 'EQ', 'Compressor', 'Formant', 'Detune and widen', 'Output'):
        if h.startswith(n): return n
    return h
def secKey(y):
    for s in secs:
        if s['r'][1] - 1 <= y < s['r'][1] + s['r'][3] - 1: return secName(s['h'])
    return ''
SKIP_SECS = ('Detune and widen', 'Output')
out = []
for it in d['items']:
    par = it['par']; r = it['r']; text = it['text']
    key = None; kind = None
    if par == 'rack':
        sec = secKey(r[1] + 2)
        if sec in SKIP_SECS: continue
        if it.get('label'): key = sec + '.' + it['label']; kind = 'knob'
        elif it['tag'] == 'button': key = sec + '.' + text; kind = 'btn'
        elif it['tag'] == 'select': key = sec + '.' + (it.get('fld') or 'Type'); kind = 'sel'
        elif it['tag'] == 'span': key = sec + '.cap.' + text; kind = 'cap'
        elif it['tag'] == 'div' and r[2] > 300: key = sec + '.head'; kind = 'head'; text = sec
        else: continue
    else:
        if it.get('label'): key = par + '.' + it['label']; kind = 'knob'
        elif it['tag'] == 'select': key = par + '.' + (it.get('fld') or text[:8]); kind = 'sel'
        elif it['tag'] == 'button': key = (it['id'] or par + '.' + text); kind = 'btn'
        elif it['tag'] == 'span': key = par + '.cap.' + text; kind = 'cap'
        elif it['id'] == 'lenInfo': key = 'lenInfo'; kind = 'info'
        elif par == 'rigHost' and it.get('label'): continue
        else: continue
    if par == 'rack' and it['tag'] == 'span' and text in ('FX rack', 'Level'): continue
    if par == 'rackcol' and it['tag'] == 'span': key = 'rackcol.' + (it['id'] or text); kind = 'cap'
    out.append((key, kind, it))
# the Host BPM knob sits in a div without the kw class path: find by label
hb = [i for i in d['items'] if i['par'] == 'rigHost' and i.get('label') == 'Host BPM']
if hb: out.append(('rigHost.Host BPM', 'knob', hb[0]))
seen = set(); rows = []
for key, kind, it in out:
    if key in seen: continue
    seen.add(key)
    knob = rc(it['knob']) if it.get('knob') else ZERO; kl = rc(it['kl']) if it.get('kl') else ZERO; kv = rc(it['kv']) if it.get('kv') else ZERO
    fld = rc(it['fldR']) if it.get('fldR') else ZERO
    txt = it.get('label') or it.get('fld') or it['text']
    if kind == 'sel': txt = it.get('fld') or it['text']
    rows.append('    { %s, %s, %s, %s, %s, %s, %s, %s, %s }' % (q(key), q(kind), q(txt), rc(it['r']), knob, kl, kv, fld, q(it['tip'])))
o = ['// GENERATED by tools/gen_layout.py from docs/mockup/layout.json. Do not edit by hand.', '#pragma once', '#include <cstring>', 'namespace layout {',
     'struct Rc { float x, y, w, h; };',
     '// kind: knob, btn, sel (select with its caption in fld), cap (text), head (rack section title row), info (readout text)',
     'struct Item { const char* key; const char* kind; const char* text; Rc r, knob, kl, kv, fld; const char* tip; };',
     'constexpr float W = 1340.0f, H = 940.0f, Cheek = 30.0f;']
for k in ('panel', 'header', 'brandSvg', 'brandName', 'brandSub', 'rig', 'srcBox', 'resBox', 'laneBox', 'ctlBox', 'rackcol', 'foot', 'sizeT', 'footL', 'cvM', 'rackInfo', 'latInfo', 'anaInfo', 'laneTabs', 'sliceRow'):
    o.append('constexpr Rc %s = %s;' % (k, rc(d[k])))
mo = [i for i in d['items'] if i['par'] == 'modes']
o.append('constexpr Rc modeTab[2] = { %s, %s };' % (rc(mo[0]['r']), rc(mo[1]['r'])))
o.append('constexpr const char* modeTip[2] = { %s, %s };' % (q(mo[0]['tip']), q(mo[1]['tip'])))
tips = d['tips']
o.append('constexpr const char* tipCheek = %s;' % q(tips['cheek'] or 'The wood side panels. Double-click one to reset the window to 100 %.'))
o.append('constexpr const char* tipSrc = %s;' % q('The whole sample. The bright part is the selection that gets stretched. Drag the orange handles; in the sampler drag the yellow slice marks.'))
o.append('constexpr const char* tipRes = %s;' % q('What the stretch engine made from the selection, with your pitch, speed and curves. The white line is the play position.'))
o.append('constexpr const char* tipLane = %s;' % q('Draw what changes over the length of the selection: pitch, speed, cutoff, formant or width. Drag a dot, click empty space to add one, double-click a dot to remove it.'))
o.append('constexpr const char* tipMeter = %s;' % q(tips['cvM'] or 'Output level of the plugin in dB (L and R peak, with a hold line).'))
rk = [s for s in secs if secName(s['h']) not in SKIP_SECS]
o.append('constexpr Rc rackSec[%d] = { %s };' % (len(rk), ', '.join(rc(s['r']) for s in rk)))
o.append('constexpr Item items[] = {\n' + ',\n'.join(rows) + ' };')
o.append('constexpr int numItems = %d;' % len(rows))
o.append('inline const Item& find(const char* key) { for (const auto& i : items) if (std::strcmp(i.key, key) == 0) return i; return items[0]; }')
o.append('inline bool has(const char* key) { for (const auto& i : items) if (std::strcmp(i.key, key) == 0) return true; return false; }')
o.append('}')
import os
os.makedirs('src/editor', exist_ok=True)
open('src/editor/Layout.h', 'w').write('\n'.join(o) + '\n')
print(len(rows), 'items'); print('\n'.join(r.split(',')[0] + ' ' + r.split(',')[1] for r in rows))
